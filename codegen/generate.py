# Rendering


def has_default(type_name: str, mod: Module, seen: set | None = None) -> bool:
    seen = seen or set()
    if type_name in seen:
        return True
    struct = mod.structs.get(type_name)
    if struct is None:
        if any(type_name == e.name for e in mod.items if isinstance(e, Enum)):
            return False
        if type_name.startswith("crate::api::") and type_name != "crate::api::Empty":
            return False
        return True
    seen.add(type_name)
    for f in struct.fields:
        if f.kind == "plain" and not has_default(f.inner.removeprefix("Box<").removesuffix(">"),
                                                 mod, seen):
            return False
    return True


def serde_attrs(f: Field) -> list[str]:
    attrs = []
    if f.kind == "vec":
        attrs.append('default, deserialize_with = "crate::api::nullable"')
        if not f.required:
            attrs.append('skip_serializing_if = "Vec::is_empty"')
    elif f.kind == "map":
        attrs.append('default, deserialize_with = "crate::api::nullable"')
        if not f.required:
            attrs.append('skip_serializing_if = "std::collections::BTreeMap::is_empty"')
    elif f.kind == "option":
        attrs.append("default")
        if not f.required:
            attrs.append('skip_serializing_if = "Option::is_none"')
    return [f"    #[serde({', '.join(attrs)})]"] if attrs else []


def param_type(rust_type: str) -> tuple[str, str]:
    """Return a setter's parameter type and the expression that converts `value`."""
    if rust_type == "String":
        return "impl Into<String>", "value.into()"
    if rust_type.startswith("Vec<"):
        elem = rust_type[4:-1]
        if elem == "String":
            return "impl IntoIterator<Item = impl Into<String>>", \
                "value.into_iter().map(Into::into).collect()"
        return f"impl IntoIterator<Item = {elem}>", "value.into_iter().collect()"
    if rust_type.startswith("Box<"):
        return rust_type[4:-1], "Box::new(value)"
    return rust_type, "value"


def render_struct(s: Struct, mod: Module) -> str:
    out = list(s.doc)
    derives = ["Debug", "Clone", "PartialEq", "serde::Serialize", "serde::Deserialize"]
    if has_default(s.name, mod):
        derives.append("Default")
    out.append(f"#[derive({', '.join(derives)})]")
    if s.input:
        out.append("#[non_exhaustive]")
    if not s.fields:
        out.append(f"pub struct {s.name} {{}}")
    else:
        out.append(f"pub struct {s.name} {{")
        for f in s.fields:
            out += doc_lines(f.doc, "    ")
            out += serde_attrs(f)
            out.append(f"    pub {field_ident(f.name)}: {f.rust_type},")
        out.append("}")

    if s.input:
        out.append("")
        out.append(f"impl {s.name} {{")
        required = [f for f in s.fields if f.required]
        params, inits = [], []
        for f in s.fields:
            ident = field_ident(f.name)
            if f.required:
                base = f.inner
                ptype, conv = param_type(base)
                conv = conv.replace("value", ident)
                params.append(f"{ident}: {ptype}")
                inits.append(f"{ident}: Some({conv})" if f.kind == "option" else
                             f"{ident}: {conv}" if conv != ident else ident)
            else:
                inits.append(f"{ident}: Default::default()")
        if required:
            out.append(f"    /// Creates a `{s.name}` with its required fields.")
        else:
            out.append(f"    /// Creates a `{s.name}` with every field left out.")
        out.append(f"    pub fn new({', '.join(params)}) -> Self {{")
        out.append(f"        Self {{ {', '.join(inits)} }}")
        out.append("    }")
        for f in s.fields:
            if f.required:
                continue
            ident = field_ident(f.name)
            base = f.inner if f.kind == "option" else f.rust_type
            ptype, conv = param_type(base)
            stored = f"Some({conv})" if f.kind == "option" else conv
            out.append("")
            out += doc_lines(f.doc, "    ")
            out.append(f"    pub fn {ident}(mut self, value: {ptype}) -> Self {{")
            out.append(f"        self.{ident} = {stored};")
            out.append("        self")
            out.append("    }")
        out.append("}")

    if s.method:
        trait = "BlockMethod" if s.block_method else "Method"
        out.append("")
        out.append(f"impl crate::api::{trait} for {s.name} {{")
        out.append(f'    const NAME: &\'static str = "{s.method}";')
        out.append(f"    type Response = {s.response};")
        out.append("}")
    return "\n".join(out)


def render_enum(e: Enum) -> str:
    out = list(e.doc)
    out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, "
               "serde::Deserialize)]")
    out.append("#[non_exhaustive]")
    out.append(f"pub enum {e.name} {{")
    for v in e.values:
        out.append(f'    #[serde(rename = "{v}")]')
        out.append(f"    {variant_ident(v)},")
    out.append("    /// A value that this version of the crate doesn't know. It can't be sent.")
    out.append("    #[serde(other, skip_serializing)]")
    out.append("    Unknown,")
    out.append("}")
    return "\n".join(out)


def render_module(mod: Module) -> str:
    out = [HEADER, f"//! {mod.doc}", ""]
    out.append("#![allow(clippy::doc_lazy_continuation, clippy::doc_overindented_list_items)]")
    out.append("")
    for item in mod.items:
        out.append(render_struct(item, mod) if isinstance(item, Struct) else render_enum(item))
        out.append("")
    return "\n".join(out)


