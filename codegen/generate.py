import subprocess
import sys
import textwrap
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HELP_JSON = ROOT / "codegen" / "help.json"
VERSION_JSON = ROOT / "codegen" / "version.json"
OUT_DIR = ROOT / "src" / "api" / "generated"
TESTS_OUT = ROOT / "tests" / "api_examples.rs"

HEADER = "// @generated by codegen/generate.py from codegen/help.json. Do not edit.\n"

RUST_KEYWORDS = {
    "as", "async", "await", "box", "break", "const", "continue", "crate", "do", "dyn", "else",
    "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in", "let", "loop",
    "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref", "return", "self",
    "static", "struct", "super", "trait", "true", "try", "type", "unsafe", "use", "virtual",
    "where", "while", "yield",
}

# Method type names that would be confusing or clash with crate items.
METHOD_NAME_OVERRIDES = {
    "block.method": "CallMethod",
}

# Nested type names, by the dotted path of the property that holds them. Paths start with the
# method name, then `in` or `out`, then property names, with `[]` for array items.
TYPE_NAME_OVERRIDES = {
    "client.key.in.key": "KeyInput",
    "client.key.in.key.key": "KeyCode",
    "client.key.in.key.action": "KeyAction",
    "block.event.in.event": "InputEvent",
    "session.float_block.in.bounds": "Bounds",
}

# Names a generated type must not take, because they would shadow the prelude.
RESERVED_NAMES = {"Box", "Default", "Error", "Option", "Result", "String", "Vec"}

# Enums with these value sets map to hand-written types in `crate::api`.
SHARED_ENUMS = {
    ("horizontal", "vertical"): "crate::api::Direction",
    ("after", "before"): "crate::api::Side",
}

# Untyped input properties with these names map to hand-written types in `crate::api`.
UNTYPED_INPUT_OVERRIDES = {
    "layout": "crate::api::Layout",
}


# --------------------------------------------------------------------------------------------
# Names


def pascal(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def singular(name: str) -> str:
    if name.endswith("ies"):
        return name[:-3] + "y"
    if name.endswith("sses") or name.endswith("xes"):
        return name[:-2]
    if name.endswith("s") and not name.endswith(("ss", "us")):
        return name[:-1]
    return name


def field_ident(name: str) -> str:
    return f"r#{name}" if name in RUST_KEYWORDS else name


def variant_ident(value: str) -> str:
    ident = pascal(value)
    if not ident or ident[0].isdigit():
        ident = "V" + ident
    return ident


# --------------------------------------------------------------------------------------------
# Docs


URL = re.compile(r"https?://[^\s)]+[^\s).,;:]")


def escape_markdown(text: str) -> str:
    """Escapes the server's plain text for rustdoc, leaving `code spans` as they are."""
    parts = text.split("`")
    for i in range(0, len(parts), 2):  # even parts are outside code spans
        part = re.sub(r"([\[\]<>])", r"\\\1", parts[i])
        parts[i] = URL.sub(lambda m: "<" + m.group(0).replace("\\", "") + ">", part)
    return "`".join(parts)


def doc_lines(text: str | None, indent: str = "") -> list[str]:
    if not text:
        return []
    text = escape_markdown(text)
    out = []
    for para in text.strip().split("\n\n"):
        wrapped = textwrap.wrap(para, width=96 - len(indent), break_on_hyphens=False) or [""]
        if out:
            out.append(f"{indent}///")
        out.extend(f"{indent}/// {line}".rstrip() for line in wrapped)
    return out


def method_docs(desc: str | None, notes: list[str] | None, wire_name: str,
                example: str | None) -> list[str]:
    lines = doc_lines(desc)
    if notes:
        lines.append("///")
        for note in notes:
            note = escape_markdown(note)
            wrapped = textwrap.wrap(note, width=92, break_on_hyphens=False)
            lines.append(f"/// - {wrapped[0]}")
            lines.extend(f"///   {w}" for w in wrapped[1:])
    lines.append("///")
    lines.append(f"/// Wire method: `{wire_name}`.")
    if example:
        lines += ["///", "/// # Example", "///", "/// ```json"]
        lines += [f"/// {line}".rstrip() for line in example.strip().splitlines()]
        lines.append("/// ```")
    return lines


