#!/usr/bin/env python3
"""Generate the typed Rex API in `src/api/generated/` from the server's help document.

The server describes its own API (`rex api list --json`, or `GET /api/help`). This script turns
that description into Rust request and response types, one module per method namespace, plus a
test file that parses every request and response example the server documents.

Usage:

    python3 codegen/generate.py            # regenerate from the snapshot in codegen/
    python3 codegen/generate.py --refresh  # update the snapshot from the local server first

The generated files are committed, so building the crate needs neither Python nor a Rex server.
"""

