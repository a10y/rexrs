# Type model


def schema_types(schema: dict) -> tuple[str | None, bool]:
    """Return the schema's base type and whether it allows null."""
    t = schema.get("type")
    if isinstance(t, list):
        nullable = "null" in t
        rest = [x for x in t if x != "null"]
        return (rest[0] if rest else None), nullable
    return t, False


def strip_docs(schema):
    if isinstance(schema, dict):
        return {k: strip_docs(v) for k, v in schema.items() if k != "description"}
    if isinstance(schema, list):
        return [strip_docs(x) for x in schema]
    return schema


def shape_key(schema: dict) -> str:
    return json.dumps(strip_docs(schema), sort_keys=True)


@dataclass
class Field:
    name: str
    rust_type: str  # the type stored in the struct, such as Option<String>
    inner: str  # the type without Option, such as String
    kind: str  # "plain", "option", "vec", "map"
    required: bool
    nullable: bool
    doc: str | None
    elem: str | None = None  # element type for vec


@dataclass
class Struct:
    name: str
    doc: list[str]
    fields: list[Field]
    input: bool = False  # used in a request, so it gets a constructor and setters
    method: str | None = None  # wire method name, for request types
    response: str | None = None
    block_method: bool = False


@dataclass
class Enum:
    name: str
    doc: list[str]
    values: list[str]


@dataclass
class Module:
    name: str
    doc: str
    items: list = field(default_factory=list)
    names: set = field(default_factory=lambda: set(RESERVED_NAMES))
    shapes: dict = field(default_factory=dict)  # shape key -> type name
    structs: dict = field(default_factory=dict)  # name -> Struct
    anchors: dict = field(default_factory=dict)  # anchor -> type name
    nullable_anchors: set = field(default_factory=set)

    def claim(self, preferred: list[str]) -> str:
        for name in preferred:
            if name not in self.names:
                self.names.add(name)
                return name
        base = preferred[-1]
        n = 2
        while f"{base}{n}" in self.names:
            n += 1
        self.names.add(f"{base}{n}")
        return f"{base}{n}"


class Generator:
    def __init__(self, module: Module):
        self.m = module

    def type_for(self, schema: dict, path: str, parent: str, prop: str, input: bool) -> str:
        """Return the Rust type for a non-null schema, registering any nested types."""
        if "$ref" in schema:
            anchor = schema["$ref"].lstrip("#")
            return f"Box<{self.m.anchors[anchor]}>"
        if "anyOf" in schema:
            objects = [s for s in schema["anyOf"] if schema_types(s)[0] == "object"]
            if objects:
                merged = dict(objects[0])
                merged.setdefault("description", schema.get("description"))
                return self.type_for(merged, path, parent, prop, input)
            return "serde_json::Value"
        base, _ = schema_types(schema)
        if "enum" in schema and base == "string":
            return self.enum_for(schema, path, parent, prop)
        if base == "string":
            return "String"
        if base == "integer":
            return "u64" if schema.get("minimum", -1) >= 0 else "i64"
        if base == "number":
            return "f64"
        if base == "boolean":
            return "bool"
        if base == "array":
            items = schema.get("items") or {}
            item_base, item_null = schema_types(items)
            inner = self.type_for(items, path + ".[]", parent, singular(prop), input)
            return f"Vec<Option<{inner}>>" if item_null and item_base else f"Vec<{inner}>"
        if base == "object":
            if schema.get("properties"):
                return self.struct_for(schema, path, parent, prop, input)
            addl = schema.get("additionalProperties")
            if isinstance(addl, dict):
                inner = self.type_for(addl, path + ".*", parent, singular(prop), input)
                return f"std::collections::BTreeMap<String, {inner}>"
            if input and prop in UNTYPED_INPUT_OVERRIDES:
                return UNTYPED_INPUT_OVERRIDES[prop]
            return "serde_json::Map<String, serde_json::Value>"
        return "serde_json::Value"

    def enum_for(self, schema: dict, path: str, parent: str, prop: str) -> str:
        values = schema["enum"]
        shared = SHARED_ENUMS.get(tuple(sorted(values)))
        if shared:
            return shared
        key = "enum:" + json.dumps(sorted(values))
        if key in self.m.shapes:
            return self.m.shapes[key]
        short = pascal(singular(prop))
        name = TYPE_NAME_OVERRIDES.get(path) or self.m.claim([short, parent + short])
        self.m.shapes[key] = name
        self.m.items.append(Enum(name, doc_lines(schema.get("description")), values))
        return name

    def struct_for(self, schema: dict, path: str, parent: str, prop: str, input: bool,
                   name: str | None = None, doc: list[str] | None = None) -> str:
        key = shape_key(schema)
        if name is None and key in self.m.shapes:
            existing = self.m.shapes[key]
            if input:
                self.mark_input(existing)
            return existing
        if name is None:
            anchor = schema.get("$anchor")
            short = pascal(singular(prop))
            preferred = [pascal(anchor)] if anchor else [short, parent + short]
            override = TYPE_NAME_OVERRIDES.get(path)
            name = override if override else self.m.claim(preferred)
            if override:
                self.m.names.add(override)
            if anchor:
                self.m.anchors[anchor] = name
                if schema_types(schema)[1]:
                    self.m.nullable_anchors.add(anchor)
            # Only nested types are shared; a method's own types belong to that method.
            self.m.shapes[key] = name
        struct = Struct(name, doc if doc is not None else doc_lines(schema.get("description")),
                        [], input=input)
        self.m.structs[name] = struct
        required = set(schema.get("required") or [])
        for fname, fschema in (schema.get("properties") or {}).items():
            struct.fields.append(self.field_for(fname, fschema, fname in required,
                                                f"{path}.{fname}", name, input))
        self.m.items.append(struct)
        return name

    def mark_input(self, name: str):
        struct = self.m.structs.get(name)
        if struct is None or struct.input:
            return
        struct.input = True
        for f in struct.fields:
            for t in re.findall(r"[A-Z][A-Za-z0-9]*", f.inner):
                self.mark_input(t)

    def field_for(self, name: str, schema: dict, required: bool, path: str, parent: str,
                  input: bool) -> Field:
        base, nullable = schema_types(schema)
        if "$ref" in schema and schema["$ref"].lstrip("#") in self.m.nullable_anchors:
            nullable = True
        inner = self.type_for(schema, path, parent, name, input)
        doc = schema.get("description")
        if inner.startswith("Vec<"):
            elem = inner[4:-1]
            return Field(name, inner, inner, "vec", required, nullable, doc, elem)
        if inner.startswith("std::collections::BTreeMap<"):
            return Field(name, inner, inner, "map", required, nullable, doc)
        if required and not nullable:
            return Field(name, inner, inner, "plain", required, nullable, doc)
        return Field(name, f"Option<{inner}>", inner, "option", required, nullable, doc)


