# Driver


MODULE_DOCS = {
    "block": "Methods that act on one block, such as closing it or sending it input.",
    "block_creator": "Methods about block creators: the kinds of block the server can make.",
    "client": "Methods that act on clients: the programs connected to the server.",
    "data": "Methods for data connections, which stream a block's output.",
    "help": "Methods that describe the server's API.",
    "hosts": "Methods that manage the server's host list.",
    "server": "Methods that act on the server itself.",
    "session": "Methods that act on sessions and the windows, layers, and blocks in them.",
    "target": "Methods that look up sessions, windows, blocks, and clients by name.",
}


def method_type_name(wire: str) -> tuple[str, str]:
    ns, _, rest = wire.partition(".")
    return ns, METHOD_NAME_OVERRIDES.get(wire) or pascal(rest)


def generate(help_doc: dict, version: dict) -> dict[str, str]:
    modules: dict[str, Module] = {}
    examples: list[tuple[str, str, str]] = []  # (test name, rust type, json)

    def module(name: str, doc: str) -> Module:
        if name not in modules:
            modules[name] = Module(name, doc)
        return modules[name]

    for m in help_doc["methods"]:
        ns, tname = method_type_name(m["name"])
        mod = module(ns, MODULE_DOCS.get(ns, f"Methods in the `{ns}` namespace."))
        mod.names.update([tname, f"{tname}Response"])
        out_schema = m.get("output_schema") or {}
        if out_schema.get("properties"):
            # Another method can return the same shape nested, such as a view inside attach.
            mod.shapes.setdefault(shape_key(out_schema), f"{tname}Response")
    for bt in help_doc.get("block_types", []):
        ns = bt["creator"].rsplit(".", 1)[-1]
        mod = module(ns, f"Methods that `{bt['creator']}` blocks provide. Call them with "
                         f"[`BlockMethod::on`](crate::api::BlockMethod::on).")
        for m in bt["methods"]:
            mod.names.update([pascal(m["name"]), f"{pascal(m['name'])}Response"])

    for m in sorted(help_doc["methods"], key=lambda m: m["name"]):
        wire = m["name"]
        ns, tname = method_type_name(wire)
        mod = module(ns, MODULE_DOCS.get(ns, f"Methods in the `{ns}` namespace."))
        gen = Generator(mod)
        mod.names.add(tname)
        resp_name = f"{tname}Response"
        mod.names.add(resp_name)

        out_schema = m.get("output_schema")
        if out_schema is None:
            resp_type = "serde_json::Value"
        elif not out_schema.get("properties"):
            resp_type = "crate::api::Empty"
        else:
            resp_type = gen.struct_for(out_schema, f"{wire}.out", tname, "response", False,
                                       name=resp_name, doc=[f"/// The result of [`{tname}`]."])

        in_schema = m.get("input_schema") or {"type": "object"}
        req = gen.struct_for(in_schema, f"{wire}.in", tname, "", True, name=tname,
                             doc=method_docs(m.get("description"), m.get("validation_notes"),
                                             wire, m.get("request_example")))
        struct = mod.structs[req]
        struct.method, struct.response = wire, resp_type
        # Fields shared with nested structs were registered before the request was marked.
        gen.mark_input(req)

        test = wire.replace(".", "_")
        if m.get("request_example"):
            examples.append((f"{test}_request", f"rexrs::api::{ns}::{tname}",
                             m["request_example"]))
        if m.get("response_example") and resp_type != "serde_json::Value":
            rtype = "rexrs::api::Empty" if resp_type == "crate::api::Empty" else \
                f"rexrs::api::{ns}::{resp_type}"
            examples.append((f"{test}_response", rtype, m["response_example"]))

    for bt in help_doc.get("block_types", []):
        creator = bt["creator"]
        ns = creator.rsplit(".", 1)[-1]
        mod = module(ns, f"Methods that `{creator}` blocks provide. Call them with "
                         f"[`BlockMethod::on`](crate::api::BlockMethod::on).")
        for m in sorted(bt["methods"], key=lambda m: m["name"]):
            gen = Generator(mod)
            tname = pascal(m["name"])
            wire = m["invoke"]["method"]
            mod.names.add(tname)
            resp_name = f"{tname}Response"
            mod.names.add(resp_name)
            out_schema = m.get("output_schema")
            if out_schema is None:
                resp_type = "serde_json::Value"
            elif not out_schema.get("properties"):
                resp_type = "crate::api::Empty"
            else:
                gen.struct_for(out_schema, f"{wire}.out", tname, "response", False,
                               name=resp_name, doc=[f"/// The result of [`{tname}`]."])
                resp_type = resp_name
            notes = [n for n in (m.get("validation_notes") or []) if "under `args`" not in n]
            req = gen.struct_for(m.get("args_schema") or {"type": "object"}, f"{wire}.in", tname,
                                 "", True, name=tname,
                                 doc=method_docs(m.get("description"), notes, wire, None))
            struct = mod.structs[req]
            struct.method, struct.response, struct.block_method = wire, resp_type, True
            gen.mark_input(req)

    files = {}
    for name, mod in sorted(modules.items()):
        files[f"{name}.rs"] = render_module(mod)

    mod_rs = [HEADER, "//! Request and response types for every method the server documents.",
              "//!", f"//! Generated from Rex {version['rex_version']}, API revision "
              f"{version['api_revision']}.", ""]
    for name in sorted(modules):
        mod_rs.append(f"pub mod {name};")
    mod_rs += ["", "/// The control API revision these types were generated for.",
               f"pub const API_REVISION: u32 = {version['api_revision']};", ""]
    files["mod.rs"] = "\n".join(mod_rs)

    tests = [HEADER, "//! Every documented request and response example parses into its type.", "",
             "#![allow(clippy::needless_borrows_for_generic_args)]", ""]
    for test, rtype, example in examples:
        tests.append("#[test]")
        tests.append(f"fn {test}() {{")
        tests.append(f'    let value: {rtype} = serde_json::from_str(r##"{example}"##).unwrap();')
        tests.append("    let json = serde_json::to_value(&value).unwrap();")
        tests.append(f"    let again: {rtype} = serde_json::from_value(json).unwrap();")
        tests.append("    assert_eq!(value, again);")
        tests.append("}")
        tests.append("")
    return files, "\n".join(tests)


def refresh():
    help_doc = subprocess.run(["rex", "api", "list", "--json"], check=True, capture_output=True,
                              text=True).stdout
    version = subprocess.run(["rex", "api", "call", "server.version"], check=True,
                             capture_output=True, text=True).stdout
    HELP_JSON.write_text(json.dumps(json.loads(help_doc), indent=1) + "\n")
    VERSION_JSON.write_text(json.dumps(json.loads(version), indent=1) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--refresh", action="store_true",
                        help="update the snapshot from the local Rex server first")
    args = parser.parse_args()
    if args.refresh:
        refresh()
    files, tests = generate(json.loads(HELP_JSON.read_text()),
                            json.loads(VERSION_JSON.read_text()))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for stale in OUT_DIR.glob("*.rs"):
        if stale.name not in files:
            stale.unlink()
    paths = []
    for name, text in files.items():
        path = OUT_DIR / name
        path.write_text(text)
        paths.append(str(path))
    TESTS_OUT.parent.mkdir(parents=True, exist_ok=True)
    TESTS_OUT.write_text(tests)
    paths.append(str(TESTS_OUT))
    subprocess.run(["rustfmt", "--edition", "2024", *paths], check=True)
    print(f"wrote {len(files)} modules and {TESTS_OUT.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
